"""Automated audio QC. Technical verification only - it says nothing about whether something is frightening.

Checks per file: integrated loudness, max short-term loudness, true peak, DC offset, clipped samples, energy
below 25 Hz and above 14 kHz relative to the whole (no subsonic or shrill content to make up for weak design),
and for loops the discontinuity at the wrap point. For the showcase: a loudness timeline + spectrogram overview,
and speech recognition over the final master to confirm what a listener can actually make out.
"""
import json
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy import signal

from .core import RATE, ROOT, loop_seam_jump, lufs, sec, short_term_max, true_peak_db

DOCS = ROOT / "docs"
QC_DIR = DOCS / "qc"


def band_ratio_db(x, lo, hi):
    mono = x.mean(axis=0) if x.ndim == 2 else x
    f, p = signal.welch(mono, RATE, nperseg=8192)
    total = np.sum(p) + 1e-30
    band = np.sum(p[(f >= lo) & (f < hi)]) + 1e-30
    return 10 * np.log10(band / total)


def analyse(path, loop=False):
    x, sr = sf.read(str(path), always_2d=True)
    x = x.T
    assert sr == RATE, (path, sr)
    stats = {
        "file": str(Path(path).relative_to(ROOT)),
        "seconds": round(x.shape[1] / sr, 2),
        "channels": x.shape[0],
        "lufs": round(lufs(x), 1),
        "true_peak": round(true_peak_db(x), 2),
        "dc": round(float(np.max(np.abs(x.mean(axis=1)))), 5),
        "clipped": int(np.sum(np.abs(x) >= 0.9999)),
        "sub25_db": round(band_ratio_db(x, 0, 25), 1),
        "air14k_db": round(band_ratio_db(x, 14000, 24000), 1),
    }
    if x.shape[1] > sec(4):
        stats["st_max"] = round(short_term_max(x), 1)
    if loop:
        stats["seam"] = round(loop_seam_jump(x), 2)
    return stats


def flags(s, limit_tp=-1.0):
    out = []
    if s["true_peak"] > limit_tp + 0.05:
        out.append("TP")
    if s["clipped"]:
        out.append("CLIP")
    if s["dc"] > 0.002:
        out.append("DC")
    if s["sub25_db"] > -20:
        out.append("SUB")
    if s["air14k_db"] > -18:
        out.append("HF")
    if s.get("seam", 0) > 1.5:
        out.append("SEAM")
    return out


def loudness_curve(x, window=3.0, hop=0.5):
    import pyloudnorm
    meter = pyloudnorm.Meter(RATE, block_size=min(window, 0.4))
    t, v = [], []
    for a in range(0, x.shape[1] - sec(window), sec(hop)):
        try:
            v.append(meter.integrated_loudness(x[:, a:a + sec(window)].T))
        except ValueError:
            v.append(-70)
        t.append((a + sec(window) / 2) / RATE)
    return np.array(t), np.maximum(np.array(v), -70)


SECTIONS = [(0, "I  ordinary"), (40, "II  first anomaly"), (78, "III  recognition"), (132, "IV  escalation"),
            (205, "V  presence"), (236, "VI  absence")]


def overview(path, out_png):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    x, sr = sf.read(str(path), always_2d=True)
    x = x.T
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(18, 7), sharex=True, gridspec_kw={"height_ratios": [2, 1]})
    mono = x.mean(axis=0)
    f, t, S = signal.spectrogram(mono, sr, nperseg=4096, noverlap=3072)
    a1.pcolormesh(t, f, 10 * np.log10(S + 1e-14), vmin=-130, vmax=-50, shading="auto", cmap="magma")
    a1.set_yscale("symlog", linthresh=300)
    a1.set_ylim(30, 20000)
    a1.set_ylabel("Hz")
    tt, lv = loudness_curve(x)
    a2.plot(tt, lv, color="#c44", lw=1)
    a2.set_ylim(-70, -5)
    a2.set_ylabel("LUFS (3 s)")
    a2.grid(alpha=.3)
    for s, name in SECTIONS:
        for ax in (a1, a2):
            ax.axvline(s, color="w" if ax is a1 else "k", alpha=.5, lw=.8)
        a1.text(s + 1, 15000, name, color="w", fontsize=9)
    a2.set_xlabel("seconds")
    plt.tight_layout()
    plt.savefig(out_png, dpi=70)
    plt.close(fig)


def transcribe(path, windows):
    """Run speech recognition over windows of the *final mix* - what a listener can plausibly make out."""
    from faster_whisper import WhisperModel
    model = WhisperModel("small.en", device="cpu", compute_type="int8")
    x, sr = sf.read(str(path), always_2d=True)
    mono = signal.resample_poly(x.mean(axis=1), 1, 3).astype(np.float32)
    out = []
    for a, b, label in windows:
        seg = mono[int(a * 16000):int(b * 16000)]
        segs, _ = model.transcribe(seg, language="en", condition_on_previous_text=False)
        text = " ".join(s.text.strip() for s in segs).strip()
        out.append((a, b, label, text or "(nothing recognised)"))
    return out


def run():
    QC_DIR.mkdir(parents=True, exist_ok=True)
    report = ["# QC report", "",
              "Generated by `python3 pipeline/build.py qc`. **Technical verification only**: these numbers prove the",
              "files are clean, consistent and safe to play; they say nothing about whether anything is frightening.",
              "", "Flags: TP true peak over -1 dBTP, CLIP clipped samples, DC offset, SUB >1% energy under 25 Hz,",
              "HF >1.6% energy over 14 kHz, SEAM loop wrap discontinuity above typical sample motion.", ""]
    master = ROOT / "showcase" / "the_register_master.flac"
    if master.exists():
        overview(master, QC_DIR / "showcase_overview.png")
        rows = [analyse(master)] + [analyse(p) for p in sorted((ROOT / "showcase" / "stems").glob("*.flac"))]
        report += ["## Showcase", "", "![overview](qc/showcase_overview.png)", "",
                    "| file | s | LUFS-I | ST max | dBTP | sub<25 dB | >14k dB | flags |", "|---|---|---|---|---|---|---|---|"]
        for s in rows:
            report.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
                s["file"], s["seconds"], s["lufs"], s.get("st_max", ""), s["true_peak"], s["sub25_db"],
                s["air14k_db"], " ".join(flags(s)) or "ok"))
        windows = [(47, 60, "PA keys up (nothing should be intelligible)"),
                   (84, 100, "counting the footsteps"),
                   (132, 158, "the register"),
                   (180, 200, "hall: crowd, hush, hymn begins"),
                   (198, 230, "hymn corrupts"),
                   (220, 236, "whispers + PA freezing"),
                   (254, 263, "the last PA line")]
        report += ["", "### What speech recognition hears in the final master", "",
                   "Whisper small.en on the mixed master. The design intends a gradient: the register and the final",
                   "line are clear; the counting is clear but distant; the whispered names sit at the threshold; the",
                   "frozen PA line breaks down.", "", "| window | intent | recognised |", "|---|---|---|"]
        for a, b, label, text in transcribe(master, windows):
            report.append("| %d-%d s | %s | %s |" % (a, b, label, text.replace("|", "/")))
    lib = ROOT / "godot" / "audio"
    manifest = lib / "manifest.json"
    if manifest.exists():
        items = json.loads(manifest.read_text())["assets"]
        report += ["", "## Interactive library", "",
                   "| asset | s | ch | LUFS-I | dBTP | seam | flags |", "|---|---|---|---|---|---|---|"]
        bad = 0
        for item in items:
            s = analyse(lib / item["file"], loop=item.get("loop", False))
            f = flags(s)
            bad += bool(f)
            report.append("| %s | %s | %s | %s | %s | %s | %s |" % (item["file"], s["seconds"], s["channels"], s["lufs"],
                                                                    s["true_peak"], s.get("seam", ""), " ".join(f) or "ok"))
        report.insert(8, "**Library: %d assets, %d flagged.**" % (len(items), bad))
        report.insert(9, "")
    (DOCS / "QC_REPORT.md").write_text("\n".join(report) + "\n")
    print("\n".join(report[:60]))
